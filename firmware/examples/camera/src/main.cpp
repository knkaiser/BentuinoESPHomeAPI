static DeviceConfig make_config() {
  DeviceConfig cfg;
  cfg.name = "example-camera";
  cfg.friendly_name = "Camera Example";
  cfg.port = 6053;
  return cfg;
}

APIServer api(make_config());
Camera webcam;

void setup() {
  Serial.begin(115200);
  delay(100);

  webcam.set_object_id("webcam");
  webcam.set_name("Webcam");
  webcam.on_image_request = [](bool single, bool stream) {
    (void)single;
    (void)stream;
    Serial.println("camera snapshot requested");
    webcam.send_image(kJpeg, sizeof(kJpeg), true);
  };

  api.add_camera(&webcam);
  connect_wifi();
  api.begin();
  advertise_api_mdns(api);
  api.enable_serial_log_bridge(LOG_LEVEL_INFO);
  Serial.println("Camera example ready");
}

void loop() { api.loop(); }
